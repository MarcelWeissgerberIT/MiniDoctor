let lang = (() => {
  try {
    const s = localStorage.getItem('md_lang');
    if (s === 'de' || s === 'en') return s;
  } catch {}
  return typeof navigator !== 'undefined' && navigator.language?.startsWith('en') ? 'en' : 'de';
})();

export function getLang() {
  return lang;
}
export function setLang(l) {
  lang = l;
  try {
    localStorage.setItem('md_lang', l);
  } catch {}
}
export function t(key, vars) {
  let s = STRINGS[lang][key] ?? STRINGS.de[key] ?? key;
  if (vars && typeof s === 'string') for (const k in vars) s = s.replace(`{${k}}`, vars[k]);
  return s;
}
