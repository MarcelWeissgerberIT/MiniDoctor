// Places: an array is [bearing°, distance] from the base (or from a group's centre),
// an object { x, z } is a fixed point of the map (north is -z, east is +x).
// a spawn: type, bearing, distance, extras (goal, path, label, tint, speed, engage)
const U = (t, b, d, extra = {}) => ({ t, b, d, ...extra });

const brief = (id, text, wait = 9, extra = {}) => ({ id: 'brief', title: 'Einsatzbefehl', text, voice: `${id}_a`, wait, done: () => true, ...extra });
const finish = (id, title, text = 'Mission erfüllt.') => ({ id: 'end', title, text, voice: `${id}_z`, wait: 8, start: (g) => g.mission.finish(), done: () => true });
/** walk to a point (bearing/distance from the base, or [x, z]) */
const march = (key, title, text, voice, at, r = 45) => ({ id: key, title, text, voice, waypoint: (g) => g.mission.waypointAt(at, title), done: (g) => g.mission.near(at, r) });
/** a group appears; the step ends when it is destroyed */
const fight = (key, title, text, voice, group, extra = {}) => ({ id: key, title, text, voice, start: (g) => g.mission.spawnGroup(key, group, extra.center), done: (g) => g.mission.cleared(key) && (!extra.also || extra.also.every((k) => g.mission.cleared(k))), ...extra });
/** hold out for a time while groups arrive on a schedule */
const hold = (key, title, text, voice, secs, schedule) => ({ id: key, title, text, voice, start: (g) => g.mission.startHold(key, secs, schedule), done: (g) => g.mission.holdDone(key) });

